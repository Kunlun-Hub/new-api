/**
 * Generate a UUID v4 string.
 *
 * `crypto.randomUUID` is only exposed in secure contexts, so deployments that
 * serve the dashboard over plain HTTP on a LAN address fall back to a
 * Math.random based generator. These identifiers are local-only (draft
 * conversations, session hints), never security tokens.
 */
export function createUuid(): string {
  if (typeof globalThis.crypto?.randomUUID === 'function') {
    return globalThis.crypto.randomUUID()
  }

  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replaceAll(/[xy]/g, (char) => {
    const random = Math.floor(Math.random() * 16)
    const value = char === 'x' ? random : (random & 0x3) | 0x8
    return value.toString(16)
  })
}
